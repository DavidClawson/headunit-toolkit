#!/usr/bin/env python3
"""gen_font.py: BDF bitmap font -> C table for gfx.c (printable ASCII, 32-126).

    gen_font.py spleen-16x32.bdf font16x32 LICENSE > font16x32.h

Each glyph is `h` rows of uint16, the row's pixels left-aligned in the low `w`
bits (bit w-1 = leftmost). Fonts with every glyph filling the full cell only
(true for Spleen). The font's license text is copied into the header.
"""
import sys

bdf, name, lic = sys.argv[1], sys.argv[2], sys.argv[3]
lines = open(bdf, encoding="latin-1").read().splitlines()
W = H = None
glyphs, cur, rows, inbm = {}, None, [], False
for ln in lines:
    p = ln.split()
    if not p: continue
    if p[0] == "FONTBOUNDINGBOX": W, H = int(p[1]), int(p[2])
    elif p[0] == "ENCODING": cur = int(p[1])
    elif p[0] == "BBX": assert (int(p[1]), int(p[2])) == (W, H), ln
    elif p[0] == "BITMAP": inbm, rows = True, []
    elif p[0] == "ENDCHAR":
        inbm = False
        if 32 <= cur <= 126: glyphs[cur] = rows
    elif inbm:
        bits = len(p[0]) * 4
        rows.append(int(p[0], 16) >> (bits - W))
assert len(glyphs) == 95 and all(len(g) == H for g in glyphs.values())
print(f"/* Generated by gen_font.py from {bdf.split('/')[-1]}: Spleen by Frederic Cambus.")
for l in open(lic).read().strip().splitlines():
    print(" * " + l if l else " *")
print(" */")
print('#include "gfx.h"')
print(f"static const uint16_t {name}_rows[95 * {H}] = {{")
for c in range(32, 127):
    print("\t" + ",".join(f"0x{r:x}" for r in glyphs[c]) + f",  /* {chr(c)!r} */" if c != 0x2a else "\t" + ",".join(f"0x{r:x}" for r in glyphs[c]) + ",  /* star */")
print("};")
print(f"const font_t {name} = {{ {W}, {H}, {name}_rows }};")
