#define G 5

static int slen(const char *s) { int n = 0; while (s[n]) n++; return n; }

static const uint8_t *strip(const uint8_t *p, int *n)  /* drop leading zero bytes */
{
	while (*n > 1 && *p == 0) { p++; (*n)--; }
	return p;
}

static void hash_num(crypto_sha512_ctx *c, const uint8_t *p, int n)
{
	p = strip(p, &n);
	crypto_sha512_update(c, p, (size_t)n);
}

static void H_k(uint8_t out[64])                       /* H(N | PAD(g)) */
{
	uint8_t g[BN_BYTES] = { 0 };
	g[BN_BYTES - 1] = G;
	crypto_sha512_ctx c;
	crypto_sha512_init(&c);
	crypto_sha512_update(&c, N3072, BN_BYTES);
	crypto_sha512_update(&c, g, BN_BYTES);
	crypto_sha512_final(&c, out);
}

void srp_start(srp_server *s, const char *user, const char *pass,
               const uint8_t salt[16], const uint8_t b[32])
{
	bn n, g, x, kb, gb, kv;
	uint8_t h[64], k[64];
	s->user = user;
	for (int i = 0; i < 16; i++) s->salt[i] = salt[i];
	bn_from_bytes(&n, N3072, BN_BYTES);
	bn_mod_init(&s->m, &n);
	bn_from_bytes(&g, (const uint8_t[]){ G }, 1);

	crypto_sha512_ctx c;                                /* x = H(salt | H(user ":" pass)) */
	crypto_sha512_init(&c);
	crypto_sha512_update(&c, (const uint8_t *)user, (size_t)slen(user));
	crypto_sha512_update(&c, (const uint8_t *)":", 1);
	crypto_sha512_update(&c, (const uint8_t *)pass, (size_t)slen(pass));
	crypto_sha512_final(&c, h);
	crypto_sha512_init(&c);
	crypto_sha512_update(&c, salt, 16);
	crypto_sha512_update(&c, h, 64);
	crypto_sha512_final(&c, h);
	bn_modexp(&s->v, &g, h, 64, &s->m);                 /* v = g^x */
	(void)x;

	bn_from_bytes(&s->b, b, 32);
	H_k(k);
	bn_from_bytes(&kb, k, 64);                          /* k < N */
	bn_modmul(&kv, &kb, &s->v, &s->m);
	bn_modexp(&gb, &g, b, 32, &s->m);
	bn_modadd(&s->B, &kv, &gb, &s->m);                  /* B = k*v + g^b */
	bn_to_bytes(s->Bbytes, &s->B);
}

int srp_finish(srp_server *s, const uint8_t *A, int alen, const uint8_t M1[64])
{
	if (alen > BN_BYTES || alen <= 0) return -1;
	uint8_t Ap[BN_BYTES] = { 0 }, Sb[BN_BYTES], u[64], bb[32], h[64], hg[64], hu[64];
	for (int i = 0; i < alen; i++) Ap[BN_BYTES - alen + i] = A[i];
	bn a, t, vu, S;
	bn_from_bytes(&a, Ap, BN_BYTES);
	if (bn_cmp(&a, &s->m.n) >= 0) return -1;
	bn_reduce(&t, &a, &s->m);
	if (bn_is_zero(&t)) return -1;                      /* A mod N must not be 0 */

	crypto_sha512_ctx c;                                /* u = H(PAD(A) | PAD(B)) */
	crypto_sha512_init(&c);
	crypto_sha512_update(&c, Ap, BN_BYTES);
	crypto_sha512_update(&c, s->Bbytes, BN_BYTES);
	crypto_sha512_final(&c, u);

	bn_modexp(&vu, &s->v, u, 64, &s->m);                /* S = (A * v^u)^b */
	bn_modmul(&t, &a, &vu, &s->m);
	{
		uint8_t full[BN_BYTES];
		bn_to_bytes(full, &s->b);
		for (int i = 0; i < 32; i++) bb[i] = full[BN_BYTES - 32 + i];
	}
	bn_modexp(&S, &t, bb, 32, &s->m);
	bn_to_bytes(Sb, &S);

	crypto_sha512_init(&c);                             /* K = H(S) */
	hash_num(&c, Sb, BN_BYTES);
	crypto_sha512_final(&c, s->K);

	uint8_t g1[1] = { G };                              /* M1 */
	crypto_sha512(h, N3072, BN_BYTES);
	crypto_sha512(hg, g1, 1);
	for (int i = 0; i < 64; i++) h[i] ^= hg[i];
	crypto_sha512(hu, (const uint8_t *)s->user, (size_t)slen(s->user));
	uint8_t m1[64];
	crypto_sha512_init(&c);
	crypto_sha512_update(&c, h, 64);
	crypto_sha512_update(&c, hu, 64);
	crypto_sha512_update(&c, s->salt, 16);
	hash_num(&c, Ap, BN_BYTES);
	hash_num(&c, s->Bbytes, BN_BYTES);
	crypto_sha512_update(&c, s->K, 64);
	crypto_sha512_final(&c, m1);
	uint8_t d = 0;
	for (int i = 0; i < 64; i++) d |= (uint8_t)(m1[i] ^ M1[i]);
	if (d) return -2;

	crypto_sha512_init(&c);                             /* M2 = H(A | M1 | K) */
	hash_num(&c, Ap, BN_BYTES);
	crypto_sha512_update(&c, m1, 64);
	crypto_sha512_update(&c, s->K, 64);
	crypto_sha512_final(&c, s->M2);
	return 0;
}
