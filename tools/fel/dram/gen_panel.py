#!/usr/bin/env python3
"""gen_panel.py: turn sys_config's [mipi_reg] list into panel_init.h.

    tools/fel/dram/gen_panel.py <sys_config_nor.fex>  > tools/fel/dram/panel_init.h

Entries are "RRVV" (register, value) or "delaymsN". Output: {reg, val} pairs,
with reg 0xFF meaning "delay val*... ms" (val holds ms, up to 255).
"""
import re, sys

src = open(sys.argv[1], encoding="latin-1").read()
block = src.split("[mipi_reg]", 1)[1].split("\n[", 1)[0]
out = []
for m in re.finditer(r'^reg(\d+)\s*=\s*"([^"]+)"', block, re.M):
    v = m.group(2).strip()
    if v.startswith("delayms"):
        out.append((0xFF, int(v[7:])))
    else:
        out.append((int(v[:2], 16), int(v[2:4], 16)))
print("/* Generated by gen_panel.py from sys_config_nor.fex [mipi_reg] (he0801a068, JD9365). */")
print("/* {reg, val}; reg 0xFF = delay val ms. */")
print(f"static const unsigned char panel_init[{len(out)}][2] = {{")
for i in range(0, len(out), 8):
    print("\t" + " ".join(f"{{0x{r:02X},0x{v:02X}}}," for r, v in out[i:i + 8]))
print("};")
